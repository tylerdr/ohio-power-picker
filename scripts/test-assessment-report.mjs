import ts from 'typescript';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const source = await fs.readFile('lib/assessment/report.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { prepareReport, packReport, recoverReport } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const intake = {caseLabel:'Synthetic broker case 001',territory:'ohio-edison',monthlyKwh:900,baselineAvailable:false,measurementGapScopeAccepted:true};
const report=prepareReport(intake);
assert.match(report,/\$87.66/); assert.match(report,/\$62.91/);
assert.match(report,/UNKNOWN/); assert.match(report,/No tariff or contract PDF/);
assert.match(report,/2026-10-22/); assert.match(report,/not a paid report/);
assert.throws(()=>prepareReport({...intake,baselineAvailable:true}),/verification/);
assert.throws(()=>prepareReport({...intake,measurementGapScopeAccepted:false}),/scope/);
for(const monthlyKwh of [NaN,Infinity,0,-1,100001]) assert.throws(()=>prepareReport({...intake,monthlyKwh}),/Invalid/);
assert.throws(()=>prepareReport({...intake,territory:'duke-energy'}),/Invalid/);
const packet=await packReport(report);
assert.equal(await recoverReport(JSON.stringify(packet)), report);
// Simulate a later template/source release: recovery must not regenerate old content.
const changed=prepareReport({...intake,monthlyKwh:1000});
assert.notEqual(changed,report); assert.equal(await recoverReport(JSON.stringify(packet)),report);
await assert.rejects(recoverReport(JSON.stringify({...packet,report:changed})),/corrupted/);
await assert.rejects(recoverReport(JSON.stringify({...packet,schema:'foreign'})),/corrupted/);
await assert.rejects(recoverReport('{invalid'),SyntaxError);
await assert.rejects(recoverReport('x'.repeat(100001)),/100 KB/);
const page=await fs.readFile('app/broker-assessment/page.tsx','utf8');
assert.match(page,/<AssessmentPreparer \/>/);
const ui=await fs.readFile('components/assessment-preparer.tsx','utf8');
assert(!ui.includes('fetch(')); assert(!ui.includes('dangerouslySetInnerHTML'));
assert.match(ui,/setError\(''\); setReport\(''\)/);
console.log('Assessment: intake bounds, scope gate, no invented baseline, dated sources/arithmetic, original-byte recovery, tamper/schema/size denial and actual page composition passed.');
